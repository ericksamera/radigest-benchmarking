#!/usr/bin/env python3
"""Phase 1 repository polish for radigest comparison workflows.

This script is intentionally conservative. It does not move scripts, rewrite
Snakefiles, rename datasets, or touch generated results.

It can:
  1. back up touched files;
  2. deduplicate duplicate Makefile target blocks, keeping the last definition;
  3. rewrite .gitignore to a single canonical version;
  4. write docs/output_contracts.md;
  5. write docs/release_checklist.md.

Default mode is dry-run. Use --apply to modify files.

Example:
  python3 scripts/phase1_polish_repository.py
  python3 scripts/phase1_polish_repository.py --apply
"""

