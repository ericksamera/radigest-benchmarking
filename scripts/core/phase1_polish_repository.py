TARGET_RE = re.compile(r"^([A-Za-z0-9_.-]+)\s*:(?![=])")
ASSIGNMENT_RE = re.compile(r"^[A-Za-z0-9_.-]+\s*(?::=|\?=|\+=|=)")


def require_repo_root() -> None:
    required = [
        Path("Makefile"),
        Path(".gitignore"),
        Path("config"),
        Path("scripts"),
        Path("workflow"),
    ]
    missing = [str(path) for path in required if not path.exists()]
    if missing:
        missing_text = ", ".join(missing)
        raise SystemExit(
            "This does not look like the radigest comparison repo root. "
            f"Missing: {missing_text}"
        )


def is_assignment(line: str) -> bool:
    return bool(ASSIGNMENT_RE.match(line))


def single_target_name(line: str) -> str | None:
    """Return a single Make target name if line starts a simple target block.

    This intentionally skips:
      - variable assignments;
      - special targets such as .PHONY;
      - multi-target rules;
      - indented recipe lines;
      - comments.
    """
    if not line.strip():
        return None
    if line.startswith(("\t", " ", "#")):
        return None
    if line.startswith("."):
        return None
    if is_assignment(line):
        return None
    if ":" not in line:
        return None

    before = line.split(":", 1)[0].strip()
    if " " in before:
        return None
    if "=" in before:
        return None

    match = TARGET_RE.match(line)
    if match is None:
        return None

    return match.group(1)


def is_top_level_boundary(line: str) -> bool:
    if not line.strip():
        return False
    if line.startswith(("\t", " ")):
        return False
    if line.startswith("#"):
        return False
    if line.startswith((".PHONY", "include ", "-include ")):
        return True
    if is_assignment(line):
        return True
    return single_target_name(line) is not None


def parse_target_blocks(lines: list[str]) -> list[tuple[str, int, int]]:
    """Return Makefile target blocks as (target, start_idx, end_idx)."""
    blocks: list[tuple[str, int, int]] = []
    i = 0

    while i < len(lines):
        target = single_target_name(lines[i])
        if target is None:
            i += 1
            continue

        start = i
        j = i + 1
        while j < len(lines):
            if is_top_level_boundary(lines[j]):
                break
            j += 1

        blocks.append((target, start, j))
        i = j

    return blocks


def dedupe_makefile_text(text: str) -> tuple[str, list[str]]:
    """Remove earlier duplicate simple-target blocks, keeping the last."""
    lines = text.splitlines(keepends=True)
    blocks = parse_target_blocks(lines)

    by_target: dict[str, list[tuple[str, int, int]]] = {}
    for block in blocks:
        target = block[0]
        by_target.setdefault(target, []).append(block)

    remove_ranges: list[tuple[int, int, str]] = []
    messages: list[str] = []

    for target in sorted(by_target):
        target_blocks = by_target[target]
        if len(target_blocks) <= 1:
            continue

        keep = target_blocks[-1]
        for block in target_blocks[:-1]:
            remove_ranges.append((block[1], block[2], target))

        messages.append(
            f"dedupe Makefile target {target!r}: kept line {keep[1] + 1}, "
            f"removed {len(target_blocks) - 1} earlier definition(s)"
        )

    if not remove_ranges:
        return text, ["No duplicate simple Makefile targets detected."]

    for start, end, _target in sorted(remove_ranges, reverse=True):
        del lines[start:end]

    return "".join(lines), messages


def backup_file(path: Path, backup_root: Path) -> Path | None:
    if not path.exists():
        return None

    backup_path = backup_root / path
    backup_path.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(path, backup_path)
    return backup_path


def write_if_changed(
    path: Path,
    content: str,
    apply: bool,
    backup_root: Path,
    messages: list[str],
) -> None:
    old = path.read_text() if path.exists() else None

    if old == content:
        messages.append(f"unchanged {path}")
        return

    if not apply:
        status = "would update" if path.exists() else "would create"
        messages.append(f"{status} {path}")
        return

    backup = backup_file(path, backup_root)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content)

    if backup is None:
        messages.append(f"created {path}")
    else:
        messages.append(f"updated {path}; backup {backup}")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--apply",
        action="store_true",
        help="Modify files. Without this flag, run in dry-run mode.",
    )
    args = parser.parse_args()

    require_repo_root()

    timestamp = dt.datetime.now().strftime("%Y%m%d_%H%M%S")
    backup_root = Path(".phase1_backups") / timestamp

    messages: list[str] = []
    messages.append(f"mode={'APPLY' if args.apply else 'DRY-RUN'}")

    makefile_path = Path("Makefile")
    makefile_text = makefile_path.read_text()
    new_makefile_text, dedupe_messages = dedupe_makefile_text(makefile_text)
    messages.extend(dedupe_messages)

    write_if_changed(
        makefile_path,
        new_makefile_text,
        args.apply,
        backup_root,
        messages,
    )
    write_if_changed(
        Path(".gitignore"),
        CANONICAL_GITIGNORE,
        args.apply,
        backup_root,
        messages,
    )
    write_if_changed(
        Path("docs/output_contracts.md"),
        OUTPUT_CONTRACTS,
        args.apply,
        backup_root,
        messages,
    )
    write_if_changed(
        Path("docs/release_checklist.md"),
        RELEASE_CHECKLIST,
        args.apply,
        backup_root,
        messages,
    )

    print("\n".join(messages))
    if not args.apply:
        print("\nNo files were modified. Re-run with --apply to write changes.")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
